<h2>কুইজ খেললে</h2>
<p>আপনার উত্তর আর ফলাফল সেভ হয়, যাতে শেয়ার করা লিংকটা কাজ করে। কার্ডে নিজের নাম লিখলে, লিংক যার কাছে আছে সে-ই নামটা দেখতে পাবে, তাই চাইলে ডাকনাম লিখুন। বন্ধুর লিংক থেকে খেললে দুজনের মিল কত, সেটাও সেভ হয়। কুইজের ফলাফলে আপনার ফোন, ইমেইল বা অ্যাকাউন্টের কোনো তথ্য থাকে না।</p>

<h2>আপনার ব্রাউজারে যা থাকে</h2>
<p>আমরা কোনো কুকি ব্যবহার করি না। ব্রাউজারের নিজস্ব জায়গায় (local storage) কয়েকটা জিনিস থাকে:</p>
<ul>
    <li>একটা এলোমেলো আইডি, যেটা দিয়ে বোঝা যায় একই ব্রাউজার আবার এসেছে কি না (আপনার নাম বা পরিচয় না)।</li>
    <li>লগইন করলে একটা টোকেন, যাতে বারবার লগইন করতে না হয়।</li>
    <li>কোন কুইজ-ফলাফল আপনার, কার্ডের কোন ডিজাইন বেছেছেন, কোন লেখায় “কাজে লেগেছে” দিয়েছেন, কোন পোস্ট সেভ করেছেন।</li>
    <li>Google বা Facebook দিয়ে লগইনের সময় অর্ধেক লেখা লেখাটা, যাতে হারিয়ে না যায়।</li>
</ul>
<p>ব্রাউজারের “site data” মুছে দিলে এগুলো সব মুছে যায়।</p>

<h2>ব্যবহারের পরিসংখ্যান</h2>
<p>সাইটটা কীভাবে ব্যবহার হচ্ছে বুঝতে আমরা নিজেরাই কিছু ঘটনা গুনি, যেমন “কুইজ শুরু হলো”, “ফলাফল শেয়ার হলো”, “আলোচনার পাতা দেখা হলো”। এগুলো ওই এলোমেলো আইডির সাথে রাখা হয়, আপনার IP ঠিকানা বা ব্রাউজারের বিস্তারিত না, শুধু ফোন / ট্যাবলেট / কম্পিউটার। কোনো বাইরের অ্যানালিটিক্স কোম্পানি নেই। এগুলো ১৮০ দিন পর মুছে যায়।</p>

<h2>আলোচনায় অ্যাকাউন্ট</h2>
<p>লেখার জন্য লগইন লাগে। কোন পদ্ধতিতে লগইন করছেন, তার ওপর নির্ভর করে আমরা রাখি:</p>
<ul>
    <li><strong>Google বা Facebook:</strong> ওই অ্যাকাউন্টের আইডি, নাম আর ইমেইল ঠিকানা।</li>
    <li><strong>ফোন:</strong> আপনার মোবাইল নম্বর।</li>
    <li><strong>ইমেইল:</strong> ইমেইল ঠিকানা আর পাসওয়ার্ড (পাসওয়ার্ড এমনভাবে রাখা হয় যে আমরাও পড়তে পারি না)।</li>
</ul>
<p>এছাড়া আপনার বেছে নেওয়া নাম, আপনার পোস্ট আর উত্তর (আর তাতে দেওয়া ছবি), “কাজে লেগেছে” চিহ্ন, রিপোর্ট, সেভ করা পোস্ট (শুধু আপনি দেখতে পান), আর আপনি বাংলা না ইংরেজিতে সাইট ব্যবহার করেন। আপনার নাম, পোস্ট আর উত্তর সবাই দেখতে পায়; ফোন নম্বর বা ইমেইল কেউ দেখতে পায় না।</p>

<h2>বেনামী পোস্ট</h2>
