<p class="mt-5">Amar Bangladesh is run by the <strong>Amar Bangladesh team</strong>. This page explains, in plain words, what the site keeps about you, why, for how long, and what you can do about it.</p>

<h2>Playing the quiz</h2>
<p>Your answers and result are saved so that the share link works. If you type your name on the card, anyone with the link can see it, so use a nickname if you prefer. If you play from a friend's link, how much you match is saved too. Quiz results hold no phone, email or account details.</p>

<h2>What your browser keeps</h2>
<p>We don't use cookies. Your browser's own storage (local storage) keeps a few things:</p>
<ul>
    <li>A random ID, so we can tell the same browser came back (not your name or identity).</li>
    <li>When you log in, a token so you don't have to log in again.</li>
    <li>Which quiz results are yours, which card design you chose, and which posts you marked “Helpful”.</li>
    <li>Text you were writing when you went to log in with Google or Facebook, so it isn't lost.</li>
</ul>
<p>Clearing the site's data in your browser removes all of these.</p>

<h2>Usage statistics</h2>
<p>To understand how the site is used, we count a few things ourselves, such as “quiz started”, “result shared”, “discussion page viewed”. They're kept with that random ID: not your IP address or browser details, only phone / tablet / computer. There is no outside analytics company. They're deleted after 180 days.</p>

<h2>Community accounts</h2>
<p>Writing needs a login. Depending on how you log in, we keep:</p>
<ul>
    <li><strong>Google or Facebook:</strong> that account's ID, name and email address.</li>
    <li><strong>Phone:</strong> your mobile number.</li>
    <li><strong>Email:</strong> your email address and password (stored so that even we can't read it).</li>
</ul>
<p>Also the name you choose, your posts and answers, your “Helpful” marks, reports, and whether you use the site in Bangla or English. Everyone can see your name, posts and answers; nobody can see your phone number or email.</p>

<h2>Anonymous posts</h2>
<p>If you post anonymously, readers never learn who wrote it: your name and profile link aren't on the page. Only the site's admins can see the author's account, and only to deal with harmful posts.</p>

<h2>Email</h2>
<p>Your email address is used only to log in, reset your password, and tell you when your question gets an answer. You can turn notification emails off from the link at the bottom of any email or on the <a href="{{ lroute('notifications', [], false) }}">Notifications</a> page. We send no ads or newsletters.</p>

<h2>Who else is involved</h2>
<ul>
    <li><strong>Google / Facebook:</strong> only if you log in with them.</li>
    <li><strong>The SMS company:</strong> gets your number to send the code if you log in by phone.</li>
    <li><strong>The email service:</strong> delivers our emails.</li>
    <li><strong>Hosting and Cloudflare:</strong> run the site and deliver it quickly; for security they may keep short-lived technical logs that include IP addresses.</li>
</ul>
<p>Nobody else gets anything, and we sell no one's data.</p>

<h2>How long we keep things</h2>
<ul>
    <li>Usage statistics and notifications: 180 days.</li>
    <li>Phone login codes: 10 minutes. Password reset links: 1 hour.</li>
    <li>Posts, answers and quiz results: until they're deleted.</li>
    <li>Accounts: until you delete them.</li>
</ul>

<h2>What you can do</h2>
<ul>
    <li>Turn off notification emails.</li>
    <li>Log out (on one device).</li>
    <li>Delete any of your posts or answers.</li>
    <li>Delete your whole account (see below).</li>
</ul>

<h2 id="delete">Deleting your account</h2>
<p>Log in, open your own page (“Me”), and choose “Delete account”. When you do:</p>
<ul>
    <li>All your ways of logging in, your email, phone number and password are deleted, and every device is logged out.</li>
    <li>Your notifications, “Helpful” marks and reports are deleted.</li>
    <li>Your posts and answers stay, so other people's questions keep their answers, but the author shows as “Deleted account” and your profile page is gone. If you prefer, tick a box to delete your posts and answers too.</li>
</ul>
<p>If you can't log in any more (for example, you lost the number or account), write to <a href="mailto:{{ $email }}">{{ $email }}</a> saying how you used to log in, and we'll delete it.</p>

